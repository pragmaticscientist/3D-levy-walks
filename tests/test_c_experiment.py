from __future__ import annotations

from ltdb_levy.c_experiment import _remove_stale_generated_configs, _slug


def test_c_condition_slug_is_safe_and_stable():
    assert _slug("cell type=T | organ=lymph node") == "cell_type_T_organ_lymph_node"
    assert _slug("../../condition") == "condition"
    assert _slug(" ") == "condition"


def test_only_stale_generated_configs_are_removed(tmp_path):
    current = tmp_path / "current.conf"
    current.write_text("# Generated by ltdb_levy; current\n", encoding="utf-8")
    stale = tmp_path / "stale.conf"
    stale.write_text("# Generated by ltdb_levy; stale\n", encoding="utf-8")
    manual = tmp_path / "manual.conf"
    manual.write_text("# maintained by a researcher\n", encoding="utf-8")

    removed = _remove_stale_generated_configs(tmp_path, {"current.conf"})

    assert removed == [stale]
    assert current.exists()
    assert manual.exists()
    assert not stale.exists()
