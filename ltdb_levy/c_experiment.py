"""Generate condition-specific configs for the existing, unmodified C simulator."""

from __future__ import annotations

import os
import json
import re
from pathlib import Path
from typing import List

import numpy as np
import pandas as pd

from .config import Config
from .dataio import ArtifactStore
from .targets import dimension_from_projected_area


def _slug(value: str) -> str:
    result = re.sub(r"[^A-Za-z0-9-]+", "_", value).strip("_-")
    return result or "condition"


def _remove_stale_generated_configs(
    directory: Path, expected_names: set
) -> List[Path]:
    """Remove obsolete configs created by an earlier fitted-condition set.

    Files without our generator marker are preserved even if they use the
    ``.conf`` suffix, so this cleanup cannot erase a hand-maintained config.
    """
    removed: List[Path] = []
    marker = "# Generated by ltdb_levy;"
    for path in directory.glob("*.conf"):
        if path.name in expected_names:
            continue
        try:
            first_line = path.open("r", encoding="utf-8").readline()
        except OSError:
            continue
        if first_line.startswith(marker):
            path.unlink()
            removed.append(path)
    return removed


def prepare_c_experiments(
    config: Config,
    num_runs: int = 2000,
    num_threads: int = 50,
) -> List[Path]:
    """Write one fitted-μ C config per successful condition and one runner.

    ``simulation.c`` stores ``l_max`` in a double config field but converts it
    to an integer before sampling. We therefore write ``ceil(data_lmax)`` and
    record both values in the index rather than allowing an implicit truncation.
    No C source is generated or modified.
    """
    if num_runs < 1 or num_threads < 1:
        raise ValueError("num_runs and num_threads must be positive")
    store = ArtifactStore(config.output.root)
    fits = store.read_frame(
        "fit",
        "mixture_fits",
        schema_name="fits",
        expected_config_hash=config.hash(),
    )
    fits = fits[fits["status"] == "ok"].sort_values("condition")
    if fits.empty:
        raise ValueError("No successful fits are available for C config generation")

    repository_root = Path(__file__).resolve().parents[1]
    config_directory = repository_root / "experiments" / "configs" / "ltdb_fitted_mu"
    config_directory.mkdir(parents=True, exist_ok=True)
    runner = repository_root / "experiments" / "detection_time_fitted_mu.sh"
    areas = ",".join("{:g}".format(value) for value in config.replay.projected_areas)
    shapes = ",".join(config.replay.shapes)
    valid_cells = []
    skipped_cells = []
    for shape in config.replay.shapes:
        for area in config.replay.projected_areas:
            dimension = dimension_from_projected_area(
                area, shape, config.replay.detection_radius
            )
            cell = {
                "shape": shape,
                "projected_area": float(area),
                "dimension": dimension,
            }
            if 1.0 <= dimension <= config.replay.domain_side_length:
                valid_cells.append(cell)
            else:
                skipped_cells.append(cell)
    expected_names = {
        "{}.conf".format(_slug(str(condition)))
        for condition in fits["condition"]
    }
    _remove_stale_generated_configs(config_directory, expected_names)
    rows = []
    outputs: List[Path] = []
    for _, fit in fits.iterrows():
        condition = str(fit["condition"])
        slug = _slug(condition)
        lmax_data = float(fit["lmax"])
        lmax_c = int(np.ceil(lmax_data))
        file_name = "detection_time_fitted_mu_{}.csv".format(slug)
        save_directory = "./outputs/{}/c_comparison/{}/".format(
            config.run_id, slug
        )
        path = config_directory / "{}.conf".format(slug)
        content = """# Generated by ltdb_levy; do not hand-edit derived parameters.
# condition={condition}
# data_lmax={lmax_data:.17g}; C-compatible lmax=ceil(data_lmax)={lmax_c}
surface_selector=2
delta_selector=0
steps_between=0
max_touches=1
num_runs={num_runs}
num_threads={num_threads}

rangemu_LevyDistrib={mu:.17g}
range_diam={areas}
range_side={side:g}
l_max={lmax_c}
range_delta=0.0

list_shapes={shapes}
range_nwalkers=1
range_ntargets=1
range_probability=1.0

save_directory={save_directory}
file_name={file_name}
""".format(
            condition=condition,
            lmax_data=lmax_data,
            lmax_c=lmax_c,
            num_runs=num_runs,
            num_threads=num_threads,
            mu=float(fit["mu_hat"]),
            areas=areas,
            side=config.replay.domain_side_length,
            shapes=shapes,
            save_directory=save_directory,
            file_name=file_name,
        )
        path.write_text(content, encoding="utf-8")
        outputs.append(path)
        rows.append(
            {
                "condition": condition,
                "config_path": str(path.relative_to(repository_root)),
                "mu_hat": float(fit["mu_hat"]),
                "data_lmax": lmax_data,
                "c_lmax": lmax_c,
                "num_runs": num_runs,
                "num_threads": num_threads,
                "output_path": save_directory + file_name,
                "analysis_hash": config.hash(),
                "expected_target_cells": len(valid_cells),
                "c_skipped_target_cells_json": json.dumps(
                    skipped_cells, sort_keys=True, separators=(",", ":")
                ),
                "support_note": "C truncates l_max to int; config uses ceil(data_lmax)",
            }
        )

    index_path = config_directory / "index.csv"
    pd.DataFrame(rows).to_csv(index_path, index=False)
    outputs.append(index_path)
    runner.write_text(
        """#!/bin/bash
set -euo pipefail

cd "$(dirname "$0")/.."
EXECUTABLE_NAME="simulation_fitted_mu_$$"
cleanup() {
    if [ -f "./$EXECUTABLE_NAME" ]; then
        rm -f "./$EXECUTABLE_NAME"
    fi
}
trap cleanup EXIT

gcc -fopenmp simulation.c func.c helpers.c -o "$EXECUTABLE_NAME" -lm

for CONFIG_FILE in ./experiments/configs/ltdb_fitted_mu/*.conf; do
    NUM_THREADS="$(awk -F= '/^num_threads=/ {print $2; exit}' "$CONFIG_FILE")"
    export OMP_NUM_THREADS="${NUM_THREADS:-1}"
    export OMP_PROC_BIND=close
    export OMP_PLACES=cores
    echo "Running $CONFIG_FILE"
    "./$EXECUTABLE_NAME" "$CONFIG_FILE"
done
""",
        encoding="utf-8",
    )
    os.chmod(runner, 0o755)
    outputs.append(runner)
    return outputs
